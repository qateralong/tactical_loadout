package tacz_camo_armor.advancement;

import net.minecraft.advancements.AdvancementHolder;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EquipmentSlot;
import net.minecraft.world.entity.LivingEntity;
import org.jetbrains.annotations.Nullable;
import tacz_camo_armor.TaczCamoArmor;
import tacz_camo_armor.camo.Camouflage;
import tacz_camo_armor.item.ArmorForm;
import tacz_camo_armor.item.ArmorSet;
import tacz_camo_armor.item.ArmorTier;
import tacz_camo_armor.item.TacticalArmorItem;

/** Advancements with code-driven criteria; their definitions are generated by ModAdvancementProvider. */
public final class ModAdvancements {
    public static final String ROOT = "root";
    public static final String SUIT_UP = "suit_up";
    public static final String GHILLIE = "ghillie";
    public static final String HELMET_SAVE = "helmet_save";
    public static final String FLASH_MOB = "flash_mob";
    public static final String EXTINGUISH = "extinguish";
    public static final String ALL_GRENADES = "all_grenades";
    public static final String DONE = "done";

    private ModAdvancements() {
    }

    public static void award(@Nullable Entity entity, String name) {
        award(entity, name, DONE);
    }

    public static void award(@Nullable Entity entity, String name, String criterion) {
        if (entity instanceof ServerPlayer player) {
            AdvancementHolder holder = player.server.getAdvancements().get(TaczCamoArmor.id("main/" + name));
            if (holder != null) {
                player.getAdvancements().award(holder, criterion);
            }
        }
    }

    public static void onEquipmentChange(LivingEntity entity, EquipmentSlot changed) {
        if (!(entity instanceof ServerPlayer player) || !changed.isArmor()) {
            return;
        }
        int heavy = 0;
        for (EquipmentSlot slot : EquipmentSlot.values()) {
            if (slot.isArmor() && player.getItemBySlot(slot).getItem() instanceof TacticalArmorItem armor
                    && armor.getEquipmentSlot() == slot && armor.tier() == ArmorTier.HEAVY) {
                heavy++;
            }
        }
        if (heavy == 4) {
            award(player, SUIT_UP);
        }
        ArmorSet camo = Camouflage.fullCamoSet(player);
        if (camo != null && camo.form() == ArmorForm.GHILLIE) {
            award(player, GHILLIE);
        }
    }
}
